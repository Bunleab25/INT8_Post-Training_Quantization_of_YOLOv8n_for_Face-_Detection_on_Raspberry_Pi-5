#!/usr/bin/env python3
"""Gate 2: build a cluster-aware deduplicated split.

Uses the audit output (reports/source_clusters.json + dataset_manifest.csv) and
creates a new dataset of symlinks, leaving the Roboflow export untouched.

  datasets/face_v2_dedup/{train,valid,test}/{images,labels}
  configs/face_v2_dedup.yaml
  splits/{train,valid,test}.txt
  reports/split_report.md
  reports/split_hashes.sha256
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import shutil
from collections import Counter, defaultdict
from pathlib import Path

SPLITS = ("train", "valid", "test")


def load_manifest(path: Path):
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def bucket(area: float) -> str:
    if area < 1024 / (416 * 416):
        return "small"
    if area < 9216 / (416 * 416):
        return "medium"
    return "large"


def split_items(items, rng):
    """80/10/10 split with at least one valid and one test item when possible."""
    items = list(items)
    rng.shuffle(items)
    n = len(items)
    if n == 1:
        return items, [], []
    if n == 2:
        return items[:1], items[1:], []
    if n == 3:
        return items[:1], items[1:2], items[2:]
    n_test = max(1, round(n * 0.10))
    n_valid = max(1, round(n * 0.10))
    n_train = n - n_valid - n_test
    return items[:n_train], items[n_train : n_train + n_valid], items[n_train + n_valid :]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="Face-Detection.v2-datasetv2.yolov8")
    ap.add_argument("--out", default="datasets/face_v2_dedup")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    root = Path(__file__).resolve().parents[1]
    dataset = (root / args.dataset).resolve()
    out = (root / args.out).resolve()
    reports = root / "reports"
    splits_dir = root / "splits"
    configs = root / "configs"
    for d in (out, reports, splits_dir, configs):
        d.mkdir(parents=True, exist_ok=True)

    clusters = json.loads((reports / "source_clusters.json").read_text(encoding="utf-8"))
    source_cluster = clusters["source_cluster"]
    cluster_best = {int(k): v for k, v in clusters["cluster_best"].items()}
    manifest = load_manifest(reports / "dataset_manifest.csv")
    row_by_path = {r["path"]: r for r in manifest}

    # One image per cluster, grouped by face-size bucket for a stratified split.
    cluster_rows = {}
    for cid, relpath in cluster_best.items():
        row = row_by_path.get(relpath)
        if row is None:
            continue
        cluster_rows[cid] = row

    buckets = defaultdict(list)
    for cid, row in cluster_rows.items():
        buckets[bucket(float(row["face_area_frac"]))].append(cid)

    rng = random.Random(args.seed)
    assigned = {}
    for bucket_name in ("large", "medium", "small"):
        tr, va, te = split_items(sorted(buckets[bucket_name]), rng)
        for cid in tr:
            assigned[cid] = "train"
        for cid in va:
            assigned[cid] = "valid"
        for cid in te:
            assigned[cid] = "test"

    # Recreate the symlink dataset.
    if out.exists():
        shutil.rmtree(out)
    for split in SPLITS:
        (out / split / "images").mkdir(parents=True, exist_ok=True)
        (out / split / "labels").mkdir(parents=True, exist_ok=True)

    split_paths = {s: [] for s in SPLITS}
    for cid, split in assigned.items():
        row = cluster_rows[cid]
        rel = Path(row["path"])
        src_img = dataset / rel
        src_lbl = dataset / rel.parent.parent / "labels" / (rel.stem + ".txt")
        dst_img = out / split / "images" / rel.name
        dst_lbl = out / split / "labels" / (rel.stem + ".txt")
        if dst_img.exists() or dst_img.is_symlink():
            dst_img.unlink()
        if dst_lbl.exists() or dst_lbl.is_symlink():
            dst_lbl.unlink()
        dst_img.symlink_to(src_img)
        if src_lbl.exists():
            dst_lbl.symlink_to(src_lbl)
        split_paths[split].append(str(rel))

    # Frozen split lists.
    for split in SPLITS:
        (splits_dir / f"{split}.txt").write_text(
            "\n".join(sorted(split_paths[split])) + "\n", encoding="utf-8"
        )

    # Dataset config (absolute path; export data.yaml stays untouched).
    names = ["Face"]
    yaml_text = f"""# Generated by scripts/make_dedup_split.py
# Cluster-aware, deduplicated split. Do not edit by hand.
path: {out}
train: train/images
val: valid/images
test: test/images
nc: {len(names)}
names: {names}
"""
    config = configs / "face_v2_dedup.yaml"
    config.write_text(yaml_text, encoding="utf-8")

    # Reproducibility hashes.
    hash_lines = []
    for split in SPLITS:
        p = splits_dir / f"{split}.txt"
        hash_lines.append(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  splits/{p.name}")
    hash_lines.append(f"{hashlib.sha256(config.read_bytes()).hexdigest()}  configs/{config.name}")
    (reports / "split_hashes.sha256").write_text("\n".join(hash_lines) + "\n", encoding="utf-8")

    # Verify: every image has a label, counts match, and no cluster spans splits.
    counts = {s: len(split_paths[s]) for s in SPLITS}
    missing_labels = 0
    for split in SPLITS:
        for p in (out / split / "images").iterdir():
            if not (out / split / "labels" / (p.stem + ".txt")).exists():
                missing_labels += 1
    cluster_split_sets = defaultdict(set)
    for cid, split in assigned.items():
        cluster_split_sets[cid].add(split)
    leakage = sum(1 for v in cluster_split_sets.values() if len(v) > 1)

    # Distribution report.
    bucket_counts = {s: Counter() for s in SPLITS}
    for cid, split in assigned.items():
        bucket_counts[split][bucket(float(cluster_rows[cid]["face_area_frac"]))] += 1

    md = [
        "# Split Report (Gate 2)",
        "",
        f"Source export: `{dataset}`",
        f"Deduplicated dataset: `{out}`",
        f"Config: `{config}`",
        f"Seed: {args.seed}",
        "",
        "## Method",
        "",
        "- Cluster all source images by perceptual hash (dHash <= 3) and source name.",
        "- Keep one (cleanest) image per cluster.",
        "- Assign **whole clusters** to train/valid/test, stratified by face-size bucket, 80/10/10.",
        "- The Roboflow export is never modified; the new dataset contains symlinks.",
        "",
        "## Counts",
        "",
        "| Split | Images | Small | Medium | Large |",
        "|---|---|---|---|---|",
    ]
    for split in SPLITS:
        c = bucket_counts[split]
        md.append(f"| {split} | {counts[split]} | {c['small']} | {c['medium']} | {c['large']} |")
    md.append(f"| **total** | **{sum(counts.values())}** | | | |")
    md += [
        "",
        "## Checks",
        "",
        f"- Missing labels: **{missing_labels}**",
        f"- Cross-split near-duplicate clusters: **{leakage}**",
        f"- Original unique sources: {len(set(source_cluster))}",
        f"- Unique clusters after dedup: {len(cluster_rows)}",
        "",
        "## Frozen files",
        "",
        "- `splits/train.txt`, `splits/valid.txt`, `splits/test.txt`",
        "- `reports/split_hashes.sha256`",
        "",
    ]

    if leakage:
        md.append("> **Gate 2 fails:** cross-split clusters remain. Investigate before training.")
    else:
        md.append("> **Gate 2 passes:** no cross-split near-duplicate clusters.")
    (reports / "split_report.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    print(f"Wrote {reports / 'split_report.md'}")
    print(json.dumps({"counts": counts, "leakage": leakage, "missing_labels": missing_labels, "config": str(config)}, indent=2))


if __name__ == "__main__":
    main()
